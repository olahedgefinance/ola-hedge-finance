"""Generate plain OLA / DEV placeholders. TEMPORARY DEV ASSET — NOT APPROVED FOR PUBLIC RELEASE.

Run from budget: python tool/brand/generate_development_assets.py [--check]
No external fonts, images, dependencies, or network access are used.
"""
from pathlib import Path
import json
import hashlib
import struct
import sys
import zlib

ROOT = Path(__file__).resolve().parents[2]
GLYPHS = {
    'O': ['01110','10001','10001','10001','10001','10001','01110'],
    'L': ['10000','10000','10000','10000','10000','10000','11111'],
    'A': ['01110','10001','10001','11111','10001','10001','10001'],
    'D': ['11110','10001','10001','10001','10001','10001','11110'],
    'E': ['11111','10000','10000','11110','10000','10000','11111'],
    'V': ['10001','10001','10001','10001','10001','01010','00100'],
}
MIDNIGHT = (11,18,32,255)
MINT = (110,231,199,255)
GOLD = (214,168,75,255)


def png(width, height, kind='standard'):
    transparent = kind in ('foreground', 'monochrome')
    bg = (0,0,0,0) if transparent else MIDNIGHT
    pixels = bytearray(bytes(bg) * width * height)
    if kind != 'background':
        # Fits Android's adaptive-icon safe region as well as legacy square icons.
        unit = max(1, min(width, height) // (40 if kind == 'foreground' else 26))
        left = (width - 17*unit)//2
        top = (height - 17*unit)//2
        for row, word in enumerate(('OLA','DEV')):
            color = (255,255,255,255) if kind == 'monochrome' else (MINT if row == 0 else GOLD)
            for index, letter in enumerate(word):
                for gy, line in enumerate(GLYPHS[letter]):
                    for gx, bit in enumerate(line):
                        if bit != '1': continue
                        for dy in range(unit):
                            y = top + (row*10+gy)*unit + dy
                            for dx in range(unit):
                                x = left + (index*6+gx)*unit + dx
                                if 0 <= x < width and 0 <= y < height:
                                    offset = (y*width+x)*4
                                    pixels[offset:offset+4] = bytes(color)
    def chunk(tag, data):
        return struct.pack('>I',len(data))+tag+data+struct.pack('>I',zlib.crc32(tag+data)&0xffffffff)
    scan = b''.join(b'\0'+pixels[y*width*4:(y+1)*width*4] for y in range(height))
    return b'\x89PNG\r\n\x1a\n'+chunk(b'IHDR',struct.pack('>IIBBBBB',width,height,8,6,0,0,0))+chunk(b'IDAT',zlib.compress(scan,9))+chunk(b'IEND',b'')


def outputs():
    manifest = json.loads((ROOT/'brand/development_assets.json').read_text(encoding='utf-8-sig'))
    for name, (w,h) in manifest['pngs'].items():
        kind = ('background' if 'ic_launcher_background' in name else
                'monochrome' if 'monochrome' in name or 'notification_icon' in name else
                'foreground' if 'foreground' in name else 'standard')
        yield ROOT/name, png(w,h,kind)
    bitmap = png(256,256)
    yield ROOT/manifest['ico'], struct.pack('<HHH',0,1,1)+struct.pack('<BBBBHHII',0,0,0,0,1,32,len(bitmap),22)+bitmap


def main():
    check = '--check' in sys.argv
    manifest = json.loads((ROOT/'brand/development_assets.json').read_text(encoding='utf-8'))
    records = {row['path']: row for row in manifest['assets']}
    from check_development_assets import PREFIXES

    failed = []
    count = 0
    for path, data in outputs():
        count += 1
        name = path.relative_to(ROOT).as_posix()
        if '..' in Path(name).parts or not name.startswith(PREFIXES):
            raise SystemExit('Refusing non-development output: '+name)
        if hashlib.sha256(data).hexdigest() != records[name]['sha256']:
            raise SystemExit('Generated bytes differ from current-development record: '+name)
        if check:
            if not path.exists() or path.read_bytes() != data: failed.append(str(path.relative_to(ROOT)))
        else:
            path.parent.mkdir(parents=True,exist_ok=True)
            path.write_bytes(data)
    if failed:
        raise SystemExit('Development assets differ: '+', '.join(failed))
    print(f'{count} temporary development assets {"verified" if check else "generated"}. Production artwork still required.')

if __name__ == '__main__': main()
